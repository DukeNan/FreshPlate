test('SEC-004 FE-005 · final HTML headers, CSP, no inline code and private API no-store', async ({ page }) => {
  const violations = []
  await page.exposeFunction('recordCspViolation', value => violations.push(value))
  await page.addInitScript(() => {
    window.__xss = false
    document.addEventListener('securitypolicyviolation', event => window.recordCspViolation({ directive: event.violatedDirective, blocked: event.blockedURI }))
  })
  const response = await page.goto('/register')
  const headers = response.headers()
  expect(headers['content-security-policy']).toContain("script-src 'self'")
  expect(headers['content-security-policy']).not.toContain('unsafe-inline')
  expect(headers['x-content-type-options']).toBe('nosniff')
  expect(headers['x-frame-options']).toBe('DENY')
  expect(headers['cache-control']).toBe('no-store')
  await page.getByLabel('用户名', { exact: true }).fill('<img onerror=__xss=true>')
  await page.getByLabel('密码', { exact: true }).fill(password)
  await page.getByRole('button', { name: '注册', exact: true }).click()
  await expect(page).toHaveURL(/\/register/)
  expect(await page.evaluate(() => window.__xss)).toBe(false)
  await register(page, 'browser_security')
  await login(page, 'browser_security')
  for (const endpoint of ['/api/me', '/api/me/preferences', '/api/auth/csrf']) {
    const result = await page.request.get(endpoint)
    expect(result.ok()).toBe(true)
    expect(result.headers()['cache-control']).toBe('no-store')
  }
  const inline = await page.evaluate(() => ({
    scripts: document.querySelectorAll('script:not([src])').length,
    styles: document.querySelectorAll('style,[style]').length,
    handlers: [...document.querySelectorAll('*')].flatMap(node => [...node.attributes]).filter(attribute => /^on/i.test(attribute.name)).length,
    storage: { ...localStorage },
  }))
  expect(inline).toEqual({ scripts: 0, styles: 0, handlers: 0, storage: {} })
  expect(violations).toEqual([])
})
test('FE-003 · failed identity recheck pauses all submissions including logout, then retries', async ({ page, context }) => {
  await register(page, 'browser_offline')
  await login(page, 'browser_offline')
  const logoutRequests = []
  page.on('request', request => { if (request.url().endsWith('/api/auth/logout')) logoutRequests.push(request) })
  await context.setOffline(true)
  await page.evaluate(() => window.dispatchEvent(new Event('focus')))
  await expect(page.getByRole('alert')).toContainText('无法确认当前身份')
  await expect(page.getByRole('button', { name: /^退出 / })).toBeDisabled()
  await expect(page.getByRole('button', { name: '保存完整设置' })).toBeDisabled()
  expect(logoutRequests).toHaveLength(0)
  await context.setOffline(false)
  await page.getByRole('button', { name: '重试身份检查' }).click()
  await expect(page.getByRole('button', { name: /^退出 / })).toBeEnabled()
  await expect(page.getByRole('button', { name: '保存完整设置' })).toBeEnabled()
  await logout(page)
  expect(logoutRequests).toHaveLength(1)
})
